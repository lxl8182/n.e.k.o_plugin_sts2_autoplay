"""Fork-local test selection.

This fork replaced the upstream tick-level planner with a companion-session
decision pipeline. A few upstream test modules assert the removed
architecture (planner calls inside ``tick``, ``_planner_context``,
heuristic ``lessons`` generated by ``summarize_run``). Their premises do not
exist here, so they are skipped instead of deleted — keeping the files intact
makes future ``git merge upstream/main`` straightforward, and the skip list
documents exactly which upstream behaviours this fork intentionally replaced.
"""

from __future__ import annotations

import pytest

_UPSTREAM_ONLY: dict[str, str] = {
    "test_plan_origin_wiring.py": (
        "本地 tick 不再调用 planner（companion 决策架构），plan_origin 接线不存在"
    ),
    "test_plan_reuse_step_consistency.py": (
        "本地 tick 没有 `_planner_context` 单一工厂（companion 决策架构）"
    ),
    "test_reflection_metrics_contract.py": (
        "本地以结构化 learning_updates 取代 summarize_run 的启发式 lessons"
    ),
}


def pytest_collection_modifyitems(config, items):
    for item in items:
        reason = _UPSTREAM_ONLY.get(item.path.name)
        if reason:
            item.add_marker(pytest.mark.skip(reason=reason))
